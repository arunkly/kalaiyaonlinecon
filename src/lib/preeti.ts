function applyMap(input: string, table: Array<[string, string]>) {
  const sorted = [...table].sort((a, b) => b[0].length - a[0].length);
  let out = "";
  let i = 0;
  while (i < input.length) {
    let hit = false;
    for (const [from, to] of sorted) {
      if (from && input.startsWith(from, i)) {
        out += to;
        i += from.length;
        hit = true;
        break;
      }
    }
    if (!hit) {
      out += input[i];
      i += 1;
    }
  }
  return out;
}

export function preetiToUnicode(text: string) {
  let s = applyMap(text, PREETI_TO_UNI);
  s = s.replace(/र्‍/g, "र्");
  s = s.replace(/((?:त्र|त्त|क्ष|ज्ञ|श्र|द्य|द्ध|ट्ट|ष्ठ|[क-ह]))ि/g, "ि$1");
  return s;
}

export function unicodeToPreeti(text: string) {
  const reversed = PREETI_TO_UNI.map(([a, b]) => [b, a] as [string, string]).filter(([from]) => from);
  let s = text.replace(/ि((?:त्र|त्त|क्ष|ज्ञ|श्र|द्य|द्ध|ट्ट|ष्ठ|[क-ह]))/g, "$1ि");
  return applyMap(s, reversed);
}
